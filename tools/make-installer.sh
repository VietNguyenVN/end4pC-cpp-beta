#!/usr/bin/env bash
# Builds the installer package (a zip) from this machine's dotfiles and from the shell's source.
#
#   tools/make-installer.sh [output-dir]      default output: ~/Public (end4pC-installer-<VERSION>.zip)
#   tools/make-installer.sh --repo            instead of a zip, refresh installer/dots and installer/fonts: what install.sh uses when it runs from a clone
#
# The zip holds installer/install.sh, the package lists (and the per-compositor ones), the niri and sway templates (refreshed first from this
# machine's ~/.config/niri and ~/.config/sway by tools/sync-installer-templates.sh), the dotfiles (kitty btop fish geany gtk-3.0 gtk-4.0
# hypr matugen kde-material-you-colors Kvantum) and the shell's source. Everything that belongs to this machine or to the person is taken out first: monitors, wallpaper paths, recent
# files, history, the built binaries, the local config. At the end the package is searched for the user name and the home path, and
# the build stops if either is found.
set -euo pipefail

PROJECT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}"
REPO_MODE=0
if [ "${1:-}" = "--repo" ]; then REPO_MODE=1; shift; fi  # --repo: refresh installer/dots and installer/fonts in this repository instead of making a zip
OUT="${1:-$HOME/Public}"
STAMP="$(tr -d '[:space:]' < "$PROJECT/VERSION")"  # the release (VERSION): beta-1, beta-2 ...
WORK="$(mktemp -d)"
NAME="end4pC-installer"
STAGE="$WORK/$NAME"
if [ -n "${KEEP_STAGE:-}" ]; then echo "(stage kept in $WORK)"; else trap 'rm -rf "$WORK"' EXIT; fi

mkdir -p "$OUT" "$STAGE/dots"

echo "==> the niri and sway templates (from the live configs)"
"$PROJECT/tools/sync-installer-templates.sh"

echo "==> installer files"
cp "$PROJECT/installer/install.sh" "$STAGE/install.sh"
cp -r "$PROJECT/installer/packages" "$STAGE/packages"
cp -a "$PROJECT/installer/templates" "$STAGE/templates"
find "$STAGE/templates" -name '__pycache__' -type d -prune -exec rm -rf {} +
cp "$PROJECT/installer/README.md" "$STAGE/README.md"
chmod +x "$STAGE/install.sh"

echo "==> fonts"
# Google Sans Flex (SIL Open Font License 1.1: it may be shared with its licence file, which is in the folder)
GSF="$HOME/.local/share/fonts/illogical-impulse-google-sans-flex"
if [ -d "$GSF" ]; then
    mkdir -p "$STAGE/fonts/illogical-impulse-google-sans-flex"
    cp "$GSF"/*.ttf "$GSF"/LICENSE "$GSF"/README.md "$STAGE/fonts/illogical-impulse-google-sans-flex/" 2>/dev/null || true
    echo "Google Sans Flex" > "$STAGE/fonts/illogical-impulse-google-sans-flex/.family"
else
    echo "    (no Google Sans Flex in $GSF: the package goes without it)"
fi

echo "==> the shell's source"
mkdir -p "$STAGE/end4pC"
tar -C "$PROJECT" \
    --exclude=./build --exclude=./.git --exclude=./.claude --exclude=./installer --exclude='__pycache__' --exclude='*.pyc' \
    --exclude=./config.json --exclude=./hyprland/local.lua \
    -cf - . | tar -C "$STAGE/end4pC" -xf -

echo "==> dotfiles"
for d in kitty btop fish geany gtk-3.0 gtk-4.0 hypr matugen kde-material-you-colors Kvantum; do
    [ -d "$CONFIG/$d" ] && cp -a "$CONFIG/$d" "$STAGE/dots/$d"
done
D="$STAGE/dots"

# single files of ~/.config
cp -a "$CONFIG/starship.toml" "$D/starship.toml"
# kdeglobals: the fonts, the icon theme, the terminal. The colours of this machine (the scheme in use and its blocks) stay out: a new
# machine gets its own from Settings -> Appearance -> Templates.
python3 - "$CONFIG/kdeglobals" "$D/kdeglobals" <<'PY'
import re, sys
src, dst = sys.argv[1], sys.argv[2]
drop_sections = re.compile(r"^\[(Colors:|ColorEffects:|WM\])")
drop_keys = ("ColorScheme=", "ColorSchemeHash=", "LastUsedCustomAccentColor=")
out, skip = [], False
for line in open(src, encoding="utf-8"):
    if line.startswith("["):
        skip = bool(drop_sections.match(line))
    if skip or line.startswith(drop_keys):
        continue
    out.append(line)
text = "".join(out)
text = re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"
open(dst, "w", encoding="utf-8").write(text)
PY

# --- what belongs to this machine or to the person is removed
rm -f  "$D/geany/session.conf" "$D/btop/btop.log" "$D/geany/".goutputstream-* "$D/geany/"geany_socket_*   # (the socket link is made while Geany runs: it names this machine)
rm -f  "$D/fish/fish_variables"                       # universal variables: generated by fish, personal
rm -f  "$D/gtk-3.0/"*-colors.css "$D/gtk-4.0/"*-colors.css   # other themes of this machine (their names are not part of the package)
rm -f  "$D/hypr/monitors.conf" "$D/hypr/sekaipop_overrides.lua"
rm -rf "$D/hypr/custom/scripts/mpvpaper_thumbnails"
find "$D" -name '__pycache__' -type d -prune -exec rm -rf {} +
find "$D" -name '*.log' -delete
find "$D" -name '*.bak' -delete
find "$D" -name '*.end4pC-backup*' -delete                  # backups the shell made of GTK/KDE files of this machine
rm -rf "$D/hypr/backup-quickshell"                          # the copy of the previous setup's binds: not part of the package

# geany: the list of recent files has paths of this machine, and the file templates have the user's name and mail
sed -i -E -e '/^(recent_files|recent_projects|session_files)/d' \
    -e 's|^(pref_template_developer)=.*|\1=Your Name|' -e 's|^(pref_template_initial)=.*|\1=YN|' \
    -e 's|^(pref_template_mail)=.*|\1=you@example.com|' "$D/geany/geany.conf" 2>/dev/null || true

# hypr: monitors that work on any screen
cat > "$D/hypr/monitors.lua" <<'LUA'
-- Any monitor, at its preferred mode, placed automatically. Replace it with yours (nwg-displays or `hyprctl monitors`).
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1 })
LUA

# hyprlock: the background of this machine's lock screen is a path
sed -i -E 's|^\$background_image *=.*$|$background_image = screenshot|' "$D/hypr/hyprlock/colors.conf" 2>/dev/null || true

# hypridle: lock with the shell's own lock screen (the file named quickshell:lock is the previous setup's)
sed -i -E "s|^\\\$lock_cmd = hyprctl dispatch 'hl.dsp.global\(\"quickshell:lock\"\)'.*$|\$lock_cmd = pidof end4pC-lock \|\| \$HOME/.config/end4pC/build/end4pC-lock|" "$D/hypr/hypridle.conf" 2>/dev/null || true

# hypr/hyprland/execs.lua: the commands of the previous setup (Quickshell) are not part of this one
if [ -f "$D/hypr/hyprland/execs.lua" ]; then
    sed -i -E \
        -e 's| \&\& qs -c \$qsConfig ipc call cliphistService update||' \
        -e 's|^(\s*)(hl\.exec_cmd\("bash ~/\.config/quickshell/.*)$|\1-- \2|' \
        "$D/hypr/hyprland/execs.lua"
fi
# the video wallpaper script is regenerated by a tool this package does not install: leave an empty one
if [ -f "$D/hypr/custom/scripts/__restore_video_wallpaper.sh" ]; then
    printf '#!/bin/bash\n# Filled in by a video wallpaper tool (mpvpaper), when you use one.\n' > "$D/hypr/custom/scripts/__restore_video_wallpaper.sh"
    chmod +x "$D/hypr/custom/scripts/__restore_video_wallpaper.sh"
fi

# colours: generated files of this machine (the first run makes them again)
rm -f "$D/hypr/hyprland/colors.conf" "$D/hypr/hyprlock/colors.conf.bak"

echo "==> check: nothing personal left"
# what is searched for comes from this machine (the user name, the home path, the git name and mail), so the script has none of it written in
patterns=("/home/$USER" "$USER@")
gitname="$(git -C "$PROJECT" config user.name 2>/dev/null || true)"
gitmail="$(git -C "$PROJECT" config user.email 2>/dev/null | cut -d@ -f1 || true)"
[ -z "$gitname" ] || patterns+=("$gitname/")
[ -z "$gitmail" ] || patterns+=("$gitmail")
# what else identifies this machine or its owner (the weather place, the screens, a tray item, the pictures), read from the machine
mapfile -t more < <("$PROJECT/tools/personal-patterns.sh")
patterns+=("${more[@]}")
bad=0
for pattern in "${patterns[@]}"; do
    # the repository address in the README is public and wanted
    hits="$(grep -rIn --exclude=README.md --exclude=README.ja.md --exclude=README.zh-CN.md  -e "$pattern" "$STAGE" 2>/dev/null | head -5 || true)"
    if [ -n "$hits" ]; then echo "found '$pattern':"; echo "$hits"; bad=1; fi
done
[ "$bad" = 0 ] || { echo "!! the package still has personal data: fix it before sharing"; exit 1; }

if [ "$REPO_MODE" = 1 ]; then
    echo "==> installer/dots and installer/fonts (for a clone of the repository)"
    rm -rf "$PROJECT/installer/dots" "$PROJECT/installer/fonts"
    cp -a "$STAGE/dots" "$PROJECT/installer/dots"
    [ -d "$STAGE/fonts" ] && cp -a "$STAGE/fonts" "$PROJECT/installer/fonts"
    echo "done: commit installer/dots and installer/fonts"
    exit 0
fi

echo "==> zip"
ZIP="$OUT/$NAME-$STAMP.zip"
rm -f "$ZIP"
( cd "$WORK" && zip -rq "$ZIP" "$NAME" )
echo "$ZIP ($(du -h "$ZIP" | cut -f1), $(unzip -Z1 "$ZIP" | grep -vc '/$') files)"

